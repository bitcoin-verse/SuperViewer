/// Embedded 8x16 Terminus bitmap font (Unicode-indexed, OFL 1.1).
/// 256 glyphs, 16 bytes per glyph (1 bit per pixel, MSB = leftmost).

pub const GLYPH_WIDTH: u32 = 8;
pub const GLYPH_HEIGHT: u32 = 16;

/// Render a line of text into an RGBA pixel buffer (premultiplied alpha).
///
/// Returns `(rgba_data, width, height)`.
pub fn render_text_line(
    text: &str,
    fg: [u8; 4],
    bg: [u8; 4],
    padding_x: u32,
    padding_y: u32,
    min_width: u32,
) -> (Vec<u8>, u32, u32) {
    let text_width = text.len() as u32 * GLYPH_WIDTH;
    let width = (text_width + 2 * padding_x).max(min_width);
    let height = GLYPH_HEIGHT + 2 * padding_y;

    // Premultiply alpha for bg and fg
    let bg_pm = premultiply(bg);
    let fg_pm = premultiply(fg);

    let mut buf = vec![0u8; (width * height * 4) as usize];
    // Fill with background
    for pixel in buf.chunks_exact_mut(4) {
        pixel.copy_from_slice(&bg_pm);
    }

    // Render each character
    for (ci, ch) in text.bytes().enumerate() {
        let glyph_idx = if ch >= 0x20 && ch < 0x80 {
            ch as usize
        } else {
            b'?' as usize
        };
        let glyph = &FONT_8X16[glyph_idx * 16..(glyph_idx + 1) * 16];
        let x0 = padding_x + ci as u32 * GLYPH_WIDTH;
        let y0 = padding_y;
        for row in 0..16u32 {
            let byte = glyph[row as usize];
            for bit in 0..8u32 {
                if (byte >> (7 - bit)) & 1 != 0 {
                    let px = x0 + bit;
                    let py = y0 + row;
                    if px < width && py < height {
                        let offset = ((py * width + px) * 4) as usize;
                        buf[offset..offset + 4].copy_from_slice(&fg_pm);
                    }
                }
            }
        }
    }

    (buf, width, height)
}

/// Render a status bar with left-aligned text and right-aligned text at a variable Y offset.
///
/// The right text's `right_y_offset` controls vertical position for ticker animation:
/// - `padding_y` (e.g. 4) = normal centered position
/// - `> height` = text is below the bar (entering from bottom)
/// - `< 0` = text is above the bar (exiting to top)
///
/// Returns `(rgba_data, width, height)`.
pub fn render_status_bar(
    left_text: &str,
    right_text: &str,
    right_y_offset: i32,
    fg: [u8; 4],
    bg: [u8; 4],
    right_colors: &[[u8; 4]],
    padding_x: u32,
    padding_y: u32,
    min_width: u32,
) -> (Vec<u8>, u32, u32) {
    let width = min_width.max(1);
    let height = GLYPH_HEIGHT + 2 * padding_y;

    let bg_pm = premultiply(bg);
    let fg_pm = premultiply(fg);

    let mut buf = vec![0u8; (width * height * 4) as usize];
    for pixel in buf.chunks_exact_mut(4) {
        pixel.copy_from_slice(&bg_pm);
    }

    // Render left text at normal position
    render_glyphs(left_text, padding_x, padding_y as i32, &fg_pm, &mut buf, width, height);

    // Render right text at variable Y offset, right-aligned
    let right_text_px = right_text.len() as u32 * GLYPH_WIDTH;
    let right_x = if width > right_text_px + padding_x {
        width - right_text_px - padding_x
    } else {
        padding_x
    };
    if right_colors.len() == right_text.len() {
        render_glyphs_colored(right_text, right_x, right_y_offset, right_colors, &mut buf, width, height);
    } else {
        render_glyphs(right_text, right_x, right_y_offset, &fg_pm, &mut buf, width, height);
    }

    (buf, width, height)
}

/// Render glyph string at (x0, y0) into buffer, with bounds clipping.
fn render_glyphs(
    text: &str,
    x0: u32,
    y0: i32,
    fg: &[u8; 4],
    buf: &mut [u8],
    width: u32,
    height: u32,
) {
    for (ci, ch) in text.bytes().enumerate() {
        let glyph_idx = if ch >= 0x20 && ch < 0x80 {
            ch as usize
        } else {
            b'?' as usize
        };
        let glyph = &FONT_8X16[glyph_idx * 16..(glyph_idx + 1) * 16];
        let gx = x0 + ci as u32 * GLYPH_WIDTH;
        for row in 0..16u32 {
            let py = y0 + row as i32;
            if py < 0 || py >= height as i32 {
                continue;
            }
            let byte = glyph[row as usize];
            for bit in 0..8u32 {
                if (byte >> (7 - bit)) & 1 != 0 {
                    let px = gx + bit;
                    if px < width {
                        let offset = ((py as u32 * width + px) * 4) as usize;
                        buf[offset..offset + 4].copy_from_slice(fg);
                    }
                }
            }
        }
    }
}

/// Render glyph string with per-character colors at (x0, y0) into buffer.
fn render_glyphs_colored(
    text: &str,
    x0: u32,
    y0: i32,
    colors: &[[u8; 4]],
    buf: &mut [u8],
    width: u32,
    height: u32,
) {
    for (ci, ch) in text.bytes().enumerate() {
        let glyph_idx = if ch >= 0x20 && ch < 0x80 {
            ch as usize
        } else {
            b'?' as usize
        };
        let glyph = &FONT_8X16[glyph_idx * 16..(glyph_idx + 1) * 16];
        let fg = &colors[ci];
        let gx = x0 + ci as u32 * GLYPH_WIDTH;
        for row in 0..16u32 {
            let py = y0 + row as i32;
            if py < 0 || py >= height as i32 {
                continue;
            }
            let byte = glyph[row as usize];
            for bit in 0..8u32 {
                if (byte >> (7 - bit)) & 1 != 0 {
                    let px = gx + bit;
                    if px < width {
                        let offset = ((py as u32 * width + px) * 4) as usize;
                        buf[offset..offset + 4].copy_from_slice(fg);
                    }
                }
            }
        }
    }
}

// CGA 16-color palette
const CGA_PALETTE: [[u8; 4]; 16] = [
    [0x00, 0x00, 0x00, 0xFF], //  0: Black
    [0x00, 0x00, 0xAA, 0xFF], //  1: Blue
    [0x00, 0xAA, 0x00, 0xFF], //  2: Green
    [0x00, 0xAA, 0xAA, 0xFF], //  3: Cyan
    [0xAA, 0x00, 0x00, 0xFF], //  4: Red
    [0xAA, 0x00, 0xAA, 0xFF], //  5: Magenta
    [0xAA, 0x55, 0x00, 0xFF], //  6: Brown
    [0xAA, 0xAA, 0xAA, 0xFF], //  7: Light Gray
    [0x55, 0x55, 0x55, 0xFF], //  8: Dark Gray
    [0x55, 0x55, 0xFF, 0xFF], //  9: Light Blue
    [0x55, 0xFF, 0x55, 0xFF], // 10: Light Green
    [0x55, 0xFF, 0xFF, 0xFF], // 11: Light Cyan
    [0xFF, 0x55, 0x55, 0xFF], // 12: Light Red
    [0xFF, 0x55, 0xFF, 0xFF], // 13: Light Magenta
    [0xFF, 0xFF, 0x55, 0xFF], // 14: Yellow
    [0xFF, 0xFF, 0xFF, 0xFF], // 15: White
];

// Indices into CGA_PALETTE to cycle through (skip black and dark gray)
const CGA_CYCLE: [usize; 14] = [9, 10, 11, 12, 13, 14, 15, 1, 2, 3, 4, 5, 6, 7];

/// Generate `count` colors cycling through the CGA palette (premultiplied RGBA).
pub fn cga_cycle_colors(count: usize) -> Vec<[u8; 4]> {
    (0..count)
        .map(|i| premultiply(CGA_PALETTE[CGA_CYCLE[i % CGA_CYCLE.len()]]))
        .collect()
}

/// Return a single CGA color by palette index (premultiplied RGBA).
pub fn cga_color(index: usize) -> [u8; 4] {
    premultiply(CGA_PALETTE[index % 16])
}

pub fn premultiply_color(c: [u8; 4]) -> [u8; 4] {
    premultiply(c)
}

/// Render a drop hint: pixel-art down-arrow icon above "Drop an image here" text.
///
/// Icon is 16x16 bitmap at 3x scale (48x48), text is 2x scale (16x32 per char).
/// Transparent background, muted grey foreground. Returns `(rgba_data, width, height)`.
pub fn render_drop_hint() -> (Vec<u8>, u32, u32) {
    let fg: [u8; 4] = [136, 136, 136, 255]; // muted grey, already opaque = premultiplied

    let text = "Drop an image here";
    let text_scale = 2u32;
    let text_char_w = GLYPH_WIDTH * text_scale;  // 16
    let text_char_h = GLYPH_HEIGHT * text_scale;  // 32
    let text_px_w = text.len() as u32 * text_char_w; // 18 * 16 = 288
    let text_px_h = text_char_h;                      // 32

    let icon_scale = 3u32;
    let icon_px = 16 * icon_scale; // 48x48
    let gap = 12u32;

    let total_w = text_px_w.max(icon_px);
    let total_h = icon_px + gap + text_px_h; // 48 + 12 + 32 = 92

    let mut buf = vec![0u8; (total_w * total_h * 4) as usize];

    // --- Render icon centered at top ---
    // 16x16 down-arrow-into-tray bitmap (1 bit per pixel, MSB-first, 2 bytes per row)
    #[rustfmt::skip]
    const ICON_16X16: [u8; 32] = [
        0x00, 0x00, // row  0: ................
        0x01, 0x80, // row  1: .......##.......
        0x01, 0x80, // row  2: .......##.......
        0x01, 0x80, // row  3: .......##.......
        0x01, 0x80, // row  4: .......##.......
        0x01, 0x80, // row  5: .......##.......
        0x01, 0x80, // row  6: .......##.......
        0x11, 0x88, // row  7: ...#...##...#...
        0x19, 0x98, // row  8: ..##...##..##...
        0x0D, 0xB0, // row  9: ....##.##.##....
        0x07, 0xE0, // row 10: .....######.....
        0x03, 0xC0, // row 11: ......####......
        0x01, 0x80, // row 12: .......##.......
        0x00, 0x00, // row 13: ................
        0x3F, 0xFC, // row 14: ..############..
        0x3F, 0xFC, // row 15: ..############..
    ];

    let icon_x0 = (total_w - icon_px) / 2;
    let icon_y0 = 0u32;
    for row in 0..16u32 {
        let b0 = ICON_16X16[(row * 2) as usize];
        let b1 = ICON_16X16[(row * 2 + 1) as usize];
        let word = ((b0 as u16) << 8) | b1 as u16;
        for bit in 0..16u32 {
            if (word >> (15 - bit)) & 1 != 0 {
                // Draw a scale x scale block
                for sy in 0..icon_scale {
                    for sx in 0..icon_scale {
                        let px = icon_x0 + bit * icon_scale + sx;
                        let py = icon_y0 + row * icon_scale + sy;
                        if px < total_w && py < total_h {
                            let off = ((py * total_w + px) * 4) as usize;
                            buf[off..off + 4].copy_from_slice(&fg);
                        }
                    }
                }
            }
        }
    }

    // --- Render text centered below icon ---
    let text_x0 = (total_w - text_px_w) / 2;
    let text_y0 = icon_px + gap;
    for (ci, ch) in text.bytes().enumerate() {
        let glyph_idx = if ch >= 0x20 && ch < 0x80 { ch as usize } else { b'?' as usize };
        let glyph = &FONT_8X16[glyph_idx * 16..(glyph_idx + 1) * 16];
        let cx = text_x0 + ci as u32 * text_char_w;
        for row in 0..16u32 {
            let byte = glyph[row as usize];
            for bit in 0..8u32 {
                if (byte >> (7 - bit)) & 1 != 0 {
                    for sy in 0..text_scale {
                        for sx in 0..text_scale {
                            let px = cx + bit * text_scale + sx;
                            let py = text_y0 + row * text_scale + sy;
                            if px < total_w && py < total_h {
                                let off = ((py * total_w + px) * 4) as usize;
                                buf[off..off + 4].copy_from_slice(&fg);
                            }
                        }
                    }
                }
            }
        }
    }

    (buf, total_w, total_h)
}

fn premultiply(c: [u8; 4]) -> [u8; 4] {
    let a = c[3] as f32 / 255.0;
    [
        (c[0] as f32 * a) as u8,
        (c[1] as f32 * a) as u8,
        (c[2] as f32 * a) as u8,
        c[3],
    ]
}

